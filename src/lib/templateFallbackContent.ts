interface FamilySpec {
  /** Обещание в долния CTA блок — с правилен род на съществителното. */
  footerPromise: string;
  usageCases: string[];
  requirements: string[];
  mistakes: string[];
  /** Специфични въпроси преди ценовия/редакционния блок. */
  faqHead: (docLower: string) => FaqItem[];
  /** Специфични въпроси след общите. */
  faqTail?: FaqItem[];
  sectionCards: SectionCard[];
  heroLegalFit: string;
  requirementsFootnote: string;
  metaLawSuffix: string;
  metaFallbackLaw: string;
  howToAnalysisText: string;
  howToFinalStepName: string;
  howToFinalStepText: string;
}

function buildFamily(
  docName: string,
  docLower: string,
  documentType: DocumentTypeId,
  f: FamilySpec,
): TemplateFallbackContent {
  return {
    unilateral: false,
    documentType,
    usageCases: f.usageCases,
    requirements: f.requirements,
    mistakes: f.mistakes,
    faq: [...f.faqHead(docLower), PRICING_FAQ(docLower), EDIT_FAQ, COMPLIANCE_FAQ, ...(f.faqTail ?? [])],
    sectionCards: f.sectionCards,
    labels: {
      usageTitle: "Кога се използва този документ",
      requirementsFootnote: f.requirementsFootnote,
      heroLegalFit: f.heroLegalFit,
      footerPromise: f.footerPromise,
      metaLawSuffix: f.metaLawSuffix,
      metaFallbackLaw: f.metaFallbackLaw,
      howToAnalysisText: f.howToAnalysisText,
      howToFinalStepName: f.howToFinalStepName,
      howToFinalStepText: f.howToFinalStepText,
    },
  };
}

