const EDIT_FAQ: FaqItem = {
  q: "Мога ли да го редактирам след генериране?",
  a: "Да. Експортираме документа в DOCX (Word) формат, който можете да редактирате допълнително преди подпис. Платените планове позволяват и редакция директно в платформата.",
};

export function buildTemplateFallbackContent(
  args: BuildTemplateFallbackArgs,
): TemplateFallbackContent {
  const { docName, categoryId } = args;
  const docLower = docName.toLowerCase();
  const unilateral = isUnilateralDocument(docName);

  if (unilateral) return buildUnilateral(docName, docLower);
  return buildBilateral(docName, docLower, categoryId);
}

