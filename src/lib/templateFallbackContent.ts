/**
 * Fallback (generic) съдържание за страницата на шаблон `/shablon/:slug`.
 *
 * Отделено в чиста, тестваема функция, защото генеричният текст трябва да е
 * ЮРИДИЧЕСКИ коректен и за ЕДНОСТРАННИ документи (молба, заявление,
 * уведомление, декларация, жалба), а не само за двустранни договори.
 *
 * Класификацията идва ЕДИНСТВЕНО от `classifyDocument`/`isUnilateralDocument`
 * в `src/data/partyRoles.ts` — тук НЕ се въвежда втори списък с ключови думи.
 */

import { isUnilateralDocument } from "@/data/partyRoles";
import { FREE_OFFER_RULE } from "@/lib/pricing";

export interface FaqItem {
  q: string;
  a: string;
}

export interface SectionCard {
  t: string;
  d: string;
}

export interface TemplateFallbackContent {
  /** true когато документът е едностранен акт (молба/заявление/декларация…). */
  unilateral: boolean;
  usageCases: string[];
  requirements: string[];
  mistakes: string[];
  faq: FaqItem[];
  /** Картите в раздел „Какво включва документът“. */
  sectionCards: SectionCard[];
  labels: {
    /** Заглавие на раздела „Кога се използва…“. */
    usageTitle: string;
    /** Ред под реквизитите (препратки към приложимо право). */
    requirementsFootnote: string;
    /** Bullet в hero-а за правно съответствие. */
    heroLegalFit: string;
    /** Обещание в долния CTA блок. */
    footerPromise: string;
    /** Опашка на meta description (когато има introExcerpt). */
    metaLawSuffix: string;
    /** Fallback meta description (когато няма introExcerpt). */
    metaFallbackLaw: string;
    /** Текст на 3-та стъпка в HowTo структурираните данни. */
    howToAnalysisText: string;
    /** Име на последната (5-та) стъпка в HowTo структурираните данни. */
    howToFinalStepName: string;
    /** Текст на последната (5-та) стъпка в HowTo структурираните данни. */
    howToFinalStepText: string;
  };
}

export interface BuildTemplateFallbackArgs {
  docName: string;
  categoryId?: string;
}

