/**
 * Категорийни чеклисти за кандидат-редакции.
 *
 * Изведени от осемте налични кандидата v2 (src/data/templateCandidates) и
 * находките, които те адресират. Кандидатите НЕ са правно одобрени — служат
 * само като еталон за структура и дисциплина, не като правна истина.
 * Всеки тип документ има свой чеклист; договорният скелет не се налага на
 * уведомления, декларации, молби или пълномощни.
 */
export type DocType =
  | "contract" | "agreement" | "notice" | "application" | "declaration"
  | "power_of_attorney" | "protocol" | "corporate_act" | "internal_policy" | "other";

const RULES: readonly [DocType, RegExp][] = [
  ["power_of_attorney", /palnomoshtno|upalnomoshtav/],
  ["corporate_act", /uchreditelen|ustav|reshenie-na|protokol-ot-obshto|obshto-sabranie|sadruzhnik|eood|ood-|-ood/],
  ["protocol", /protokol/],
  ["declaration", /deklaratsiya|deklaracia/],
  ["notice", /predizvestie|uvedomlenie|pokana|pretenziya|reklamatsiya|izvestie|nastoyavane|pismo/],
  ["application", /molba|zayavlenie|iskane|zayavka/],
  ["agreement", /sporazumenie|anex|aneks|spogodba/],
  ["internal_policy", /politika|pravilnik|vatreshni-pravila|instruktsiya|registar|zapoved/],
  ["contract", /dogovor/],
];

export function classifyDocType(slug: string): DocType {
  for (const [t, re] of RULES) if (re.test(slug)) return t;
  return "other";
}

