export function pickRandomQuote(previousIndex?: number): { quote: BusinessQuote; index: number } {
  if (BUSINESS_QUOTES.length <= 1) return { quote: BUSINESS_QUOTES[0], index: 0 };
  let i = Math.floor(Math.random() * BUSINESS_QUOTES.length);
  if (previousIndex !== undefined && i === previousIndex) {
    i = (i + 1) % BUSINESS_QUOTES.length;
  }
  return { quote: BUSINESS_QUOTES[i], index: i };
}
