const cache = new Map<string, string | null>();

/** Връща правна подсказка за полето или null, ако няма подходяща. */
export function getFieldHint(id: string, label: string): string | null {
  const key = `${id}::${label}`;
  const cached = cache.get(key);
  if (cached !== undefined) return cached;
  const haystack = `${id} ${label}`.toLowerCase();
  const found = RULES.find((r) => r.match.test(haystack))?.hint ?? null;
  cache.set(key, found);
  return found;
}
