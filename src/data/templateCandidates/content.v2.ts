export interface ContentCandidate {
  slug: string;
  version: string;
  status: "candidate_draft";
  legalApproval: null;
  content: TemplateContent;
  /** Въпрос → използвани прочетени източници. */
  sourceIds: Readonly<Record<string, readonly string[]>>;
}

type Patch = { q: string; a: string; law?: string; sources: string[] };

function patch(base: TemplateContent, edits: Readonly<Record<string, Patch>>, extra: Partial<TemplateContent> = {}): { content: TemplateContent; sourceIds: Record<string, string[]> } {
  const sourceIds: Record<string, string[]> = {};
  const faq = base.faq.map((f) => {
    const e = edits[f.q];
    if (!e) return f;
    sourceIds[e.q] = e.sources;
    return { q: e.q, a: e.a, ...(e.law ? { law: e.law } : {}) };
  });
  const missing = Object.keys(edits).filter((q) => !base.faq.some((f) => f.q === q));
  if (missing.length) throw new Error(`content patch: въпросът не съществува в оригинала: ${missing.join("; ")}`);
  return { content: { ...base, ...extra, faq }, sourceIds };
}

