export type NoticeBasis = keyof typeof BODIES;

export function buildNotice(basis: NoticeBasis, role: Role): CandidateScenario {
  const b = BODIES[basis];
  const ret = basis === "rescission" ? "" : `\n\n${returnClause(role)}`;
  return {
    id: `${basis}.${role}`,
    label: `${b.label} — автор ${ROLE[role][0].toLowerCase()}`,
    decisiveFields: b.decisive,
    preconditions: "preconditions" in b ? b.preconditions : undefined,
    text: `${b.title}\n\n${parties(role)}\n\n${b.body}${ret}\n\n${closing(role)}`,
  };
}

