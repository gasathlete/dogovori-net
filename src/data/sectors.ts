export type FieldType = "text" | "textarea" | "number" | "date" | "select" | "radio";

export interface Question {
  id: string;
  label: string;
  help?: string;
  type: FieldType;
  options?: string[];
  placeholder?: string;
  required?: boolean;
  /** Conditionally show this question */
  showIf?: (answers: Record<string, string>) => boolean;
}

export interface SubWizard {
  /** Точното име от каталога (CatalogDocument.name) */
  documentName: string;
  /** Override на contractName за LiveDraft */
  contractName?: string;
  /** Override на наименованието на страните */
  parties?: { a: string; b: string };
  /** Специфични въпроси, които се добавят след категорийните */
  questions: Question[];
}

export interface Sector {
  id: string;
  title: string;
  subtitle: string;
  icon: string; // lucide name
  description: string;
  contractName: string;
  parties: { a: string; b: string };
  questions: Question[];
  subWizards?: SubWizard[];
}

