// Compact helpers за специфични въпроси
const t = (id: string, label: string, placeholder?: string, required = true): Question =>
  ({ id, label, type: "text", placeholder, required });
const ta = (id: string, label: string, placeholder?: string, required = true): Question =>
  ({ id, label, type: "textarea", placeholder, required });
const n = (id: string, label: string, placeholder?: string, required = true): Question =>
  ({ id, label, type: "number", placeholder, required });
const d = (id: string, label: string, required = true): Question =>
  ({ id, label, type: "date", required });
const sel = (id: string, label: string, options: string[], required = true): Question =>
  ({ id, label, type: "select", options, required });
const rad = (id: string, label: string, options: string[], required = true): Question =>
  ({ id, label, type: "radio", options, required });
const sub = (documentName: string, questions: Question[], contractName?: string, parties?: { a: string; b: string }): SubWizard =>
  ({ documentName, contractName, parties, questions });

