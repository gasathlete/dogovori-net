/**
 * Fills missing rich SEO content for catalog templates that don't yet have a
 * matching file under src/data/templateContent/<slug>.ts.
 *
 * Source of truth for the slug = the same logic prerender.ts and the sitemap
 * builder use (slugify(doc.name) + dedup suffix per CATALOG order).
 *
 * For each missing slug, asks Lovable AI to produce:
 *   - intro (2–3 sentences, SEO-optimized)
 *   - 3–5 usageCases
 *   - 5–8 requirements (BG law specific)
 *   - 4–6 mistakes
 *   - 5–6 FAQ Q&A pairs
 *
 * Writes one file per template (`src/data/templateContent/<slug>.ts`) in the
 * same shape as the existing split files. Resume-friendly: skips slugs that
 * already have a file. Also refreshes templateContentMeta.json and the
 * loader index after the run.
 *
 * Usage: bun run scripts/fill-missing-template-content.ts [maxToGenerate]
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { CATALOG } from "../src/data/catalog";
import { slugify } from "../src/lib/slugify";

const API_KEY = process.env.LOVABLE_API_KEY;
if (!API_KEY) {
  console.error("LOVABLE_API_KEY not set");
  process.exit(1);
}

const MODEL = "google/gemini-2.5-flash";
const ENDPOINT = "https://ai.gateway.lovable.dev/v1/chat/completions";
const CONTENT_DIR = join(process.cwd(), "src/data/templateContent");
const META_JSON = join(process.cwd(), "src/data/templateContentMeta.json");
const INDEX_TS = join(CONTENT_DIR, "index.ts");

const MAX = process.argv[2] ? Number(process.argv[2]) : Infinity;

interface TemplateContent {
  intro: string;
  usageCases: string[];
  requirements: string[];
  mistakes: string[];
  faq: { q: string; a: string }[];
}

const SYSTEM = `Ти си български юрист с 15 години опит и експерт по SEO съдържание. Пишеш ясно, точно, на правен български. Цитираш конкретни закони (ЗЗД, ТЗ, КТ, ЗУТ, ЗЗП, GDPR/ЗЗЛД, ЗДДС). Никога не измисляш членове или закони.`;

function buildPrompt(name: string, purpose: string, keyClause: string, category: string): string {
  return `Изготви SEO-оптимизирано съдържание за страница за договор/документ:

Име: "${name}"
Категория: "${category}"
Цел: ${purpose}
Ключова клауза: ${keyClause}

Върни СТРОГО JSON със следната структура (без markdown, без обяснения):
{
  "intro": "2-3 изречения въведение, естествено включващо ключовите думи. Без клишета.",
  "usageCases": ["3 до 5 конкретни сценария кога се използва"],
  "requirements": ["5 до 8 задължителни реквизита за този конкретен договор по българското право"],
  "mistakes": ["4 до 6 най-чести грешки при изготвянето на този конкретен договор"],
  "faq": [{"q": "Въпрос?", "a": "Отговор в 1-3 изречения, съдържащ цитиране на закон ако е приложимо."}]
}

Изисквания: faq да има 5-6 въпроса. Отговорите да са фактически точни и специфични за БЪЛГАРСКОТО право.`;
}

async function generate(name: string, purpose: string, keyClause: string, category: string): Promise<TemplateContent | null> {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(ENDPOINT, {
        method: "POST",
        headers: { "Content-Type": "application/json", Authorization: `Bearer ${API_KEY}` },
        body: JSON.stringify({
          model: MODEL,
          messages: [
            { role: "system", content: SYSTEM },
            { role: "user", content: buildPrompt(name, purpose, keyClause, category) },
          ],
          response_format: { type: "json_object" },
        }),
      });
      if (res.status === 429) {
        console.warn(`  rate limited, waiting 15s...`);
        await new Promise((r) => setTimeout(r, 15000));
        continue;
      }
      if (!res.ok) {
        console.error(`  HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`);
        return null;
      }
      const data = await res.json();
      const text = data.choices?.[0]?.message?.content;
      if (!text) return null;
      const parsed = JSON.parse(text) as TemplateContent;
      if (!parsed.intro || !Array.isArray(parsed.faq) || parsed.faq.length < 3) {
        console.warn(`  invalid output shape, retrying`);
        continue;
      }
      return parsed;
    } catch (e: any) {
      console.error(`  error: ${e.message}, retry ${attempt + 1}`);
      await new Promise((r) => setTimeout(r, 2000));
    }
  }
  return null;
}

function writeContentFile(slug: string, content: TemplateContent) {
  const body = `// AUTO-GENERATED by scripts/fill-missing-template-content.ts
import type { TemplateContent } from "../templateContentTypes";

const content: TemplateContent = ${JSON.stringify(content, null, 2)};

export default content;
`;
  writeFileSync(join(CONTENT_DIR, `${slug}.ts`), body, "utf8");
}

function refreshIndexAndMeta() {
  const files = readdirSync(CONTENT_DIR).filter((f) => f.endsWith(".ts") && f !== "index.ts");
  const slugs = files.map((f) => f.replace(/\.ts$/, "")).sort();

  const entries = slugs
    .map((s) => `  ${JSON.stringify(s)}: () => import("./${s}").then((m) => m.default),`)
    .join("\n");

  const indexBody = `// AUTO-GENERATED by scripts/fill-missing-template-content.ts
import type { TemplateContent } from "../templateContentTypes";

export type TemplateContentLoader = () => Promise<TemplateContent>;

const loaders: Record<string, TemplateContentLoader> = {
${entries}
};

export function loadTemplateContent(slug: string): Promise<TemplateContent> | undefined {
  const fn = loaders[slug];
  return fn ? fn() : undefined;
}

export const TEMPLATE_CONTENT_SLUGS = ${JSON.stringify(slugs, null, 2)} as const;
`;
  writeFileSync(INDEX_TS, indexBody, "utf8");

  // Update meta JSON with introExcerpts
  const meta: Record<string, { introExcerpt: string }> = {};
  for (const slug of slugs) {
    try {
      const raw = readFileSync(join(CONTENT_DIR, `${slug}.ts`), "utf8");
      const m = raw.match(/content\s*:\s*TemplateContent\s*=\s*(\{[\s\S]*?\});\s*\n+\s*export\s+default/);
      if (m) {
        const obj = JSON.parse(m[1]);
        meta[slug] = { introExcerpt: (obj.intro || "").slice(0, 200) };
      }
    } catch { /* skip */ }
  }
  writeFileSync(META_JSON, JSON.stringify(meta, null, 2), "utf8");
  console.log(`✓ index.ts and templateContentMeta.json refreshed (${slugs.length} slugs)`);
}

async function main() {
  mkdirSync(CONTENT_DIR, { recursive: true });
  const existing = new Set(
    readdirSync(CONTENT_DIR).filter((f) => f.endsWith(".ts") && f !== "index.ts").map((f) => f.replace(/\.ts$/, "")),
  );

  const tasks: Array<{ slug: string; name: string; purpose: string; keyClause: string; category: string }> = [];
  const used = new Set<string>();
  for (const cat of CATALOG) {
    for (const doc of cat.documents) {
      let base = slugify(doc.name) || "shablon";
      let slug = base;
      let i = 2;
      while (used.has(slug)) slug = `${base}-${i++}`;
      used.add(slug);
      if (!existing.has(slug)) {
        tasks.push({ slug, name: doc.name, purpose: doc.purpose, keyClause: doc.keyClause, category: cat.title });
      }
    }
  }
  console.log(`Found ${tasks.length} missing templateContent files (cap: ${MAX === Infinity ? "all" : MAX})`);

  const toRun = tasks.slice(0, MAX);
  let ok = 0, fail = 0;
  for (let i = 0; i < toRun.length; i++) {
    const t = toRun[i];
    console.log(`[${i + 1}/${toRun.length}] ${t.slug}`);
    const c = await generate(t.name, t.purpose, t.keyClause, t.category);
    if (c) {
      writeContentFile(t.slug, c);
      ok++;
    } else {
      fail++;
      console.error(`  FAILED: ${t.slug}`);
    }
    // Re-index every 25 successes so partial runs are also usable.
    if (ok > 0 && ok % 25 === 0) refreshIndexAndMeta();
    await new Promise((r) => setTimeout(r, 350));
  }

  refreshIndexAndMeta();
  console.log(`\nDone. generated=${ok} failed=${fail}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
