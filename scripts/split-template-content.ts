/**
 * One-off splitter: src/data/templateContent.ts (1.9 MB) -->
 *   - src/data/templateContentMeta.ts          (sync, ~30 KB: title + intro excerpt per slug)
 *   - src/data/templateContent/<slug>.ts       (one file per template, full content)
 *   - src/data/templateContent/index.ts        (slug -> () => import("./<slug>"))
 *
 * Run with: bun run scripts/split-template-content.ts
 */
import { mkdirSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { join } from "node:path";

// Dynamically import the source. We rely on tsx/bun being able to load TS files.
import { TEMPLATE_CONTENT, type TemplateContent } from "../src/data/templateContent";

const OUT_DIR = join(process.cwd(), "src/data/templateContent");
const META_FILE = join(process.cwd(), "src/data/templateContentMeta.ts");

if (existsSync(OUT_DIR)) rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

const sluggedFiles: string[] = [];
const metaEntries: Array<{ slug: string; introExcerpt: string }> = [];

const safeFile = (slug: string) => slug.replace(/[^a-z0-9-_]/gi, "_");

for (const [slug, content] of Object.entries(TEMPLATE_CONTENT) as Array<[string, TemplateContent]>) {
  const file = `${safeFile(slug)}.ts`;
  sluggedFiles.push(slug);

  const intro = (content.intro ?? "").trim();
  metaEntries.push({ slug, introExcerpt: intro.slice(0, 200) });

  const body = `// AUTO-GENERATED by scripts/split-template-content.ts
import type { TemplateContent } from "../templateContentTypes";

const content: TemplateContent = ${JSON.stringify(content, null, 2)};

export default content;
`;
  writeFileSync(join(OUT_DIR, file), body, "utf8");
}

// Index: slug -> dynamic import
const indexEntries = sluggedFiles
  .map((slug) => `  ${JSON.stringify(slug)}: () => import("./${safeFile(slug)}").then((m) => m.default),`)
  .join("\n");

const indexBody = `// AUTO-GENERATED by scripts/split-template-content.ts
import type { TemplateContent } from "../templateContentTypes";

export type TemplateContentLoader = () => Promise<TemplateContent>;

const loaders: Record<string, TemplateContentLoader> = {
${indexEntries}
};

export function loadTemplateContent(slug: string): Promise<TemplateContent> | undefined {
  const fn = loaders[slug];
  return fn ? fn() : undefined;
}

export function hasTemplateContent(slug: string): boolean {
  return slug in loaders;
}
`;
writeFileSync(join(OUT_DIR, "index.ts"), indexBody, "utf8");

// Shared types file (referenced by both the meta file and per-slug files).
writeFileSync(
  join(process.cwd(), "src/data/templateContentTypes.ts"),
  `// AUTO-GENERATED by scripts/split-template-content.ts
export interface TemplateContent {
  intro: string;
  usageCases: string[];
  requirements: string[];
  mistakes: string[];
  faq: { q: string; a: string; law?: string }[];
}
`,
  "utf8",
);

// Sync meta file (small, eager, used for SEO meta tags).
const metaObj: Record<string, { introExcerpt: string }> = {};
for (const { slug, introExcerpt } of metaEntries) metaObj[slug] = { introExcerpt };

writeFileSync(
  META_FILE,
  `// AUTO-GENERATED by scripts/split-template-content.ts
// Sync metadata used for SEO (<meta description>, JSON-LD) — keep small.
export interface TemplateContentMeta {
  introExcerpt: string;
}

export const TEMPLATE_CONTENT_META: Record<string, TemplateContentMeta> = ${JSON.stringify(metaObj, null, 2)};
`,
  "utf8",
);

console.log(`Wrote ${sluggedFiles.length} per-slug files to ${OUT_DIR}`);
console.log(`Wrote ${META_FILE}`);
